// Package account описывает, что comment-service делает с данными
// пользователя, удалившего аккаунт.
package account

import "context"

// DeletedAuthorID — автор обезличенного комментария.
//
// Настоящие user_id начинаются с 1, поэтому 0 ни с кем не совпадёт: править
// или удалять такой комментарий от чужого имени нельзя. Профиль с этим
// идентификатором не найдётся, и выдача покажет автора без имени.
const DeletedAuthorID uint = 0

// Repository стирает данные пользователя.
//
// Комментарии не удаляются, а обезличиваются: на них отвечали другие люди, и
// удаление оборвало бы чужие ветки. Лайки удаляются — они не несут смысла без
// автора.
//
// Повторный вызов для того же пользователя безопасен и ничего не меняет.
type Repository interface {
	EraseUser(ctx context.Context, userID uint) error
}
