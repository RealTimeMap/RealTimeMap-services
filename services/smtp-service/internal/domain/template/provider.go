// Package template описывает источник шаблонов писем.
//
// Шов между MVP и фазой 2: сейчас шаблоны лежат в embed.FS и катятся вместе с
// кодом; позже переезжают в Postgres с версиями, ревизиями и редактированием
// через админку. Всё, что стоит за Provider, об этом не знает — подмена
// реализации происходит в app.Container.
package template

import "context"

// Template — шаблон письма вместе с его контрактом на входные данные.
type Template struct {
	ID      string
	Version uint

	// Subject — тема письма. Тоже шаблон: может содержать плейсхолдеры.
	Subject string
	HTML    string

	// RequiredData — поля, без которых рендер обязан завершиться ошибкой.
	// Без этой проверки отсутствующее поле подставляется пустой строкой, и
	// письмо уходит с «Здравствуйте, !» — молча и необратимо.
	RequiredData []string
}

// Provider отдаёт шаблон по идентификатору.
//
// version == nil означает «последняя». Параметр присутствует с самого начала,
// хотя embed-реализация его игнорирует: в фазе 2 админка выбирает версию явно,
// и добавление параметра задним числом потребовало бы правки всех вызовов.
type Provider interface {
	Get(ctx context.Context, templateID string, version *uint) (*Template, error)
}
