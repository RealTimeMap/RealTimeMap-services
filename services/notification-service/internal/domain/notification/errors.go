package notification

import "errors"

// Классы ошибок отправки. Определяют реакцию воркера на неудачу.
//
// Реализация Sender обязана отнести ошибку провайдера к одному из классов,
// обернув её так, чтобы исходная сохранилась для логов. Без классификации
// воркер не отличает мёртвый токен от кратковременного сбоя сети и одинаково
// ретраит оба: отозванный токен будет выбирать max_attempt на каждом
// уведомлении, бесконечно.
var (
	// ErrTransient — временный отказ: сеть, таймаут, недоступность провайдера,
	// исчерпанная квота. Уведомление возвращается в очередь с отложенным
	// ScheduledAt.
	ErrTransient = errors.New("transient send error")

	// ErrPermanent — отказ, который не пройдёт сам: испорченное сообщение,
	// токен от чужого проекта, непринятые провайдером креды. Повтор ничего
	// не изменит, уведомление помечается failed.
	ErrPermanent = errors.New("permanent send error")

	// ErrTokenInvalid — токен больше не действителен: приложение удалено,
	// переустановлено или токен обновился.
	//
	// Отдельный класс, а не частный случай ErrPermanent: реакция другая —
	// не только бросить уведомление, но и отозвать токен в БД, иначе все
	// последующие отправки на него будут проваливаться так же.
	ErrTokenInvalid = errors.New("device token is no longer valid")
)
