// Package account описывает, что mark-service делает с данными
// пользователя, удалившего аккаунт.
package account

import "context"

// Repository физически удаляет данные пользователя: публичные и личные
// метки, списки, лайки и счётчик ревизий синхронизации.
//
// Метки удаляются, а не обезличиваются: в них геопозиция, фото и имя —
// обезличенная метка «у моего дома» остаётся указанием на человека. Мягкое
// удаление не годится по той же причине: строка с данными остаётся в БД.
//
// Лайки других людей на удалённых метках удаляются вместе с метками.
//
// Файлы фотографий в хранилище не удаляются: оно content-addressed, и один
// объект может принадлежать нескольким меткам разных пользователей.
//
// Повторный вызов для того же пользователя безопасен и ничего не меняет.
type Repository interface {
	EraseUser(ctx context.Context, userID uint) error
}
