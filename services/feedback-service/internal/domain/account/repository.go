// Package account описывает, что feedback-service делает с данными
// пользователя, удалившего аккаунт.
package account

import "context"

// Repository обезличивает отчёты пользователя.
//
// Отчёты не удаляются: по ним идёт работа над багами, а подтверждённые уже
// привязаны к задачам в таск-менеджере. Стираются автор, IP и логи
// приложения — в логах могут оказаться координаты и имена, и гарантировать
// обратное нельзя. Текст отчёта и сведения об устройстве остаются: без
// автора они на человека не указывают.
//
// Повторный вызов для того же пользователя безопасен и ничего не меняет.
type Repository interface {
	EraseUser(ctx context.Context, userID uint) error
}
